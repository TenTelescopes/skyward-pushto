"""Build docs/data/bounds.js: IAU constellation boundaries (B1875) from Stellarium's modern_iau sky culture
(source edges: https://pbarbier.com/constellations/edges_18.txt). Only parallels (constant-Dec edges) are needed for
the northward ray test."""
import json, sys
d = json.load(open(sys.argv[1]))
def hms(s): h, m, x = s.split(':'); return 15 * (int(h) + int(m) / 60 + float(x) / 3600)
def dms(s): sg = -1 if s[0] == '-' else 1; dd, m, x = s.lstrip('+-').split(':'); return sg * (int(dd) + int(m) / 60 + float(x) / 3600)
P = []
for e in d['edges']:
    p = e.split()
    if p[1][0] != 'P': continue
    P.append([round(hms(p[2]), 5), round(hms(p[4]), 5), round(dms(p[3]), 5), p[6], p[7]])
names = {}
for c in d['constellations']:
    ab = c['id'].split()[-1].upper(); names[ab] = c['common_name'].get('native') or c['common_name'].get('english')
names['SER1'] = names['SER2'] = names.get('SER', 'Serpens')
js = "// Generated by tools/build_bounds.py — IAU constellation boundaries, B1875 parallels: [ra1, ra2, dec, conA, conB] (degrees).\n"
js += "// Source: Stellarium modern_iau sky culture (edges from pbarbier.com/constellations/edges_18.txt).\n"
js += "export const PARALLELS = " + json.dumps(P, separators=(',', ':')) + ";\n"
js += "export const CON_FULL = " + json.dumps(names, separators=(',', ':')) + ";\n"
open(sys.argv[2], 'w').write(js); print(len(P), 'parallels', len(names), 'names')
